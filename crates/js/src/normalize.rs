//! `String.prototype.normalize` for the scripts pages actually run it on:
//! Latin letters with diacritics (slugs, search folding, Vietnamese).
//! Other text is passed through, which is right for text already in NFC.

/// NFD (`compose == false`) or NFC of `s`.
pub fn normalize(s: &str, compose: bool) -> String {
    let mut out = String::with_capacity(s.len() + 8);
    for c in s.chars() {
        decompose(c, &mut out);
    }
    if !compose {
        return out;
    }
    let mut composed = String::with_capacity(out.len());
    let mut last: Option<char> = None;
    for c in out.chars() {
        if let Some(base) = last {
            if let Some(m) = compose_pair(base, c) {
                last = Some(m);
                continue;
            }
            composed.push(base);
        }
        last = Some(c);
    }
    if let Some(c) = last {
        composed.push(c);
    }
    composed
}

fn decompose(c: char, out: &mut String) {
    let cp = c as u32;
    if cp < 0xC0 {
        out.push(c);
        return;
    }
    match LATIN_DECOMP.binary_search_by_key(&cp, |r| r.0) {
        Ok(k) => {
            let (_, base, mark) = LATIN_DECOMP[k];
            decompose(char::from_u32(base).unwrap_or(c), out);
            out.push(char::from_u32(mark).unwrap_or(c));
        }
        Err(_) => out.push(c),
    }
}

fn compose_pair(base: char, mark: char) -> Option<char> {
    let (b, m) = (base as u32, mark as u32);
    if !(0x300..0x370).contains(&m) {
        return None;
    }
    LATIN_DECOMP.iter().find(|r| r.1 == b && r.2 == m).and_then(|r| char::from_u32(r.0))
}

